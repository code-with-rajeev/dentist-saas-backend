# Standard library
import uuid

# Third-party
from sqlalchemy import CheckConstraint, ForeignKey, SmallInteger, String, Text, Index
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

# Internal
from app.database.base import Base
from app.database.mixins import TimestampMixin, SoftDeleteMixin


class Patient(Base, TimestampMixin, SoftDeleteMixin):
    """
    Patients registered under a clinic.
    Soft deleted — never hard delete patient data.
    Full-text search supported on full_name via GIN index in migration.
    """

    __tablename__ = "patients"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    clinic_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("clinics.id", ondelete="RESTRICT"),
        nullable=False,
    )

    # Human-readable display ID — Format: PAT-YYYY-NNNNN
    # Generated by app/utils/id_generator.py
    patient_code: Mapped[str] = mapped_column(String(20), nullable=False)

    # Core info
    full_name: Mapped[str] = mapped_column(String(120), nullable=False)
    age: Mapped[int] = mapped_column(SmallInteger, nullable=False)
    gender: Mapped[str | None] = mapped_column(String(10), nullable=True)

    # Contact — all optional
    phone: Mapped[str | None] = mapped_column(String(20), nullable=True)
    email: Mapped[str | None] = mapped_column(String(150), nullable=True)

    # Persistent patient notes (allergies, chronic conditions)
    general_notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Relationships
    appointments: Mapped[list["Appointment"]] = relationship(
        "Appointment",
        back_populates="patient",
        cascade="all, delete-orphan",
        lazy="selectin",
    )

    __table_args__ = (
        # Unique patient_code per clinic
        Index(
            "uq_patients_code_clinic",
            "clinic_id",
            "patient_code",
            unique=True,
        ),
        # Index for name search — clinic-scoped
        Index("idx_patients_clinic_id", "clinic_id"),
        Index("idx_patients_full_name", "clinic_id", "full_name"),
        Index("idx_patients_phone", "clinic_id", "phone"),
        CheckConstraint("age > 0 AND age < 121", name="ck_patients_age_range"),
    )

    def __repr__(self) -> str:
        return f"<Patient id={self.id} name={self.full_name} code={self.patient_code}>"
